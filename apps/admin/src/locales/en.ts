/**
 * Every word the admin panel says, in English.
 *
 * One file per language, and this is the only one that ships. Adding a language
 * means copying this file, translating the values, and adding it to `./index` --
 * nothing else changes, and the settings screen offers it the moment it exists
 * because that list is derived from these files rather than maintained beside
 * them.
 *
 * Keys are dotted and grouped by where they appear, not by what they say: two
 * screens that happen to say "Save" get their own key, because they will not
 * always say the same thing in every language, and a shared key is how a
 * translator loses the ability to tell them apart.
 *
 * `{name}` is a value the caller supplies. A key that is missing renders as the
 * key itself, which is the same choice the theme's `t` filter makes: it shows up
 * on the screen instead of quietly rendering nothing.
 */

